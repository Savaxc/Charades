export const CATEGORY_MAP = Object.fromEntries(
  CATEGORIES.map((category) => [category.id, category]),
) as Record<CategoryId, Category>;

export const UNKNOWN_CATEGORY = CATEGORIES[0];

export const CATEGORY_GROUPS: Array<{
  id: 'screen' | 'other';
  title: string;
  ids: CategoryId[];
}> = [
  {
    id: 'screen',
    title: 'Film i serije',
    ids: ['domestic-movies', 'foreign-movies', 'domestic-series', 'foreign-series'],
  },
  {
    id: 'other',
    title: 'Ostalo',
    ids: ['music', 'animals', 'acting'],
  },
];

export function getCategory(categoryId: CategoryId | null): Category {
  if (!categoryId) return UNKNOWN_CATEGORY;
  return CATEGORY_MAP[categoryId] ?? UNKNOWN_CATEGORY;
}

export function getCategories(categoryIds: CategoryId[]): Category[] {
  return categoryIds
    .map((categoryId) => CATEGORY_MAP[categoryId])
    .filter((category): category is Category => Boolean(category));
}
